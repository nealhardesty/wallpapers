#!/usr/bin/env node
// Make World Clock's coastline, web/wallpapers/world-clock/world-land.js,
// from Natural Earth's 1:110m land polygons (public domain).
//
//   node tools/world-land.mjs              download ne_110m_land.geojson
//   node tools/world-land.mjs <file>       or read a copy of it
//
// Each ring is simplified (Douglas–Peucker, TOLERANCE degrees), quantized to
// tenths of a degree, and written as one flat list of integers: the first
// point, then each step from the one before. WorldClockMath.land() decodes it.
// The same input always gives the same file, byte for byte.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

// A release tag, not master, so a regeneration gives the same file.
const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson';
const OUT = join(resolve(import.meta.dirname, '..'), 'web/wallpapers/world-clock/world-land.js');
const TOLERANCE = 0.05;     // degrees: half the grid, so only redundant points go (about 25 KB)
const SCALE = 10;           // tenths of a degree

const path = process.argv[2];
const geojson = path ? JSON.parse(readFileSync(path, 'utf8')) : await (async () => {
    const response = await fetch(SOURCE);
    if (!response.ok) throw new Error(`world-land: ${SOURCE} answered ${response.status}`);
    return response.json();
})();

// Perpendicular distance from p to the segment a–b, in degrees on the flat map.
function distance(p, a, b) {
    const dx = b[0] - a[0], dy = b[1] - a[1], length = dx * dx + dy * dy;
    const t = length ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / length)) : 0;
    return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy);
}

function simplify(points, from, to, keep) {
    let worst = 0, at = -1;
    for (let i = from + 1; i < to; i++) {
        const d = distance(points[i], points[from], points[to]);
        if (d > worst) { worst = d; at = i; }
    }
    if (worst > TOLERANCE) {
        keep[at] = true;
        simplify(points, from, at, keep);
        simplify(points, at, to, keep);
    }
}

// A closed ring: anchored at its first point and the point farthest from it.
function simplifyRing(ring) {
    const points = ring.slice(0, -1);                       // GeoJSON repeats the first point at the end
    let far = 0;
    points.forEach((p, i) => { if (Math.hypot(p[0] - points[0][0], p[1] - points[0][1]) > Math.hypot(points[far][0] - points[0][0], points[far][1] - points[0][1])) far = i; });
    const keep = points.map((_, i) => i === 0 || i === far);
    const closed = [...points, points[0]];
    simplify(closed, 0, far, keep);
    simplify(closed, far, points.length, keep);
    return points.filter((_, i) => keep[i]);
}

function encode(points) {
    const q = [];
    for (const [lon, lat] of points) {
        const p = [Math.round(lon * SCALE), Math.round(lat * SCALE)];
        const last = q[q.length - 1];
        if (!last || last[0] !== p[0] || last[1] !== p[1]) q.push(p);
    }
    while (q.length > 1 && q[0][0] === q[q.length - 1][0] && q[0][1] === q[q.length - 1][1]) q.pop();
    if (q.length < 3) return null;                          // an islet smaller than the grid
    const out = [...q[0]];
    for (let i = 1; i < q.length; i++) out.push(q[i][0] - q[i - 1][0], q[i][1] - q[i - 1][1]);
    return out.map(n => String(n + 0)).join(',');           // + 0: never "-0"
}

const rings = [];
for (const { geometry } of geojson.features) {
    const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.type === 'MultiPolygon' ? geometry.coordinates : [];
    for (const polygon of polygons) for (const ring of polygon) {
        const encoded = encode(simplifyRing(ring));
        if (encoded) rings.push(encoded);
    }
}
if (rings.length < 100) throw new Error(`world-land: only ${rings.length} rings; is this ne_110m_land?`);

const text = `// World Clock's land: Natural Earth 1:110m land polygons (ne_110m_land),
// public domain (see THIRD_PARTY.md). Generated by \`make world-land\`
// (tools/world-land.mjs); don't edit by hand.
//
// One flat list of integers per ring, in tenths of a degree: the first
// [lon, lat], then each step from the point before. Rings are closed
// implicitly; lakes are rings too, so fill with 'evenodd'.
// WorldClockMath.land() decodes them.

const WORLD_LAND = [
${rings.map(r => `[${r}]`).join(',\n')}
];
`;
writeFileSync(OUT, text);
console.log(`world-land: ${rings.length} rings, ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB → web/wallpapers/world-clock/world-land.js`);
